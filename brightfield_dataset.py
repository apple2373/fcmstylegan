"""PyTorch dataset for the files produced by ``preprocess_task1_images.py``."""

from __future__ import annotations

import csv
from pathlib import Path

import numpy as np
import torch
from PIL import Image
from torch import Tensor
from torch.utils.data import Dataset


class BrightFieldProfileDataset(Dataset):
    """Load preprocessed brightfield images and profile conditions.

    The dataset uses every row in the CSV.  The CSV is not used to scan the
    output directory; it supplies the cell IDs used to construct the exact
    preprocessed filenames.

    Parameters
    ----------
    csv_path:
        Path to ``task1_dataset_split.csv``.
    preprocessed_root:
        Directory containing the files generated by the preprocessing script.
    id_column:
        Required CSV column containing the cell IDs.
    mode:
        ``"pad"`` loads ``*_cropped_pad128.png`` and
        ``*_profiles_pad128.npz``. ``"resize"`` loads the corresponding
        ``resize128`` files.
    orientation:
        ``"horizontal"`` or ``"vertical"``.
    normalized:
        Select the precomputed normalized brightfield PNG. Profiles have no
        separate normalized archive in the preprocessing output, so the
        profile archive is unchanged by this option.

    Returns
    -------
    dict
        ``image``: float tensor with shape ``(1, 128, 128)``.
        ``profile``: float tensor with shape ``(3, 128)`` ordered as SSC,
        CD45, and mask.
    """

    def __init__(
        self,
        csv_path: str | Path,
        preprocessed_root: str | Path,
        *,
        id_column: str,
        mode: str = "pad",
        orientation: str = "horizontal",
        normalized: bool = False,
    ) -> None:
        if mode not in {"pad", "resize"}:
            raise ValueError("mode must be 'pad' or 'resize'")
        if orientation not in {"horizontal", "vertical"}:
            raise ValueError("orientation must be 'horizontal' or 'vertical'")

        self.preprocessed_root = Path(preprocessed_root)
        self.mode = mode
        self.orientation = orientation
        self.normalized = normalized

        with Path(csv_path).open(newline="") as file:
            reader = csv.DictReader(file)
            if reader.fieldnames is None:
                raise ValueError("CSV must contain a header")
            if id_column not in reader.fieldnames:
                raise ValueError(f"CSV has no id column {id_column!r}")
            self.rows = list(reader)

        if not self.rows:
            raise ValueError("CSV contains no samples")

        self.id_column = id_column

    def __len__(self) -> int:
        return len(self.rows)

    def __getitem__(self, index: int) -> dict[str, Tensor | dict[str, str]]:
        metadata = dict(self.rows[index])
        cell_id = metadata[self.id_column]
        image_path = self._image_path(cell_id)
        profile_path = self._profile_path(cell_id)

        # These are already padded/resized/normalized by preprocessing.
        # Keep the dataset/model contract explicit: grayscale images in [-1, 1].
        image = np.asarray(Image.open(image_path).convert("L"), dtype=np.float32)
        image = image / 127.5 - 1.0
        profiles = np.load(profile_path, allow_pickle=False)
        profile_keys = [
            f"{self.orientation}_ssc",
            f"{self.orientation}_cd45",
            f"{self.orientation}_mask",
        ]

        try:
            profile = np.stack([profiles[key] for key in profile_keys], axis=0)
        except KeyError as error:
            profiles.close()
            raise KeyError(f"{profile_path} is missing profile key {error.args[0]!r}") from error
        profiles.close()

        return {
            "image": torch.from_numpy(np.ascontiguousarray(image[None])).float(),
            "profile": torch.from_numpy(np.ascontiguousarray(profile)).float(),
            "metadata": metadata,
        }

    def _image_path(self, cell_id: str) -> Path:
        suffix = "_normalized" if self.normalized else ""
        path = self.preprocessed_root / (
            f"{cell_id}_brightfield_cropped_{self.mode}128{suffix}.png"
        )
        if not path.is_file():
            raise FileNotFoundError(path)
        return path

    def _profile_path(self, cell_id: str) -> Path:
        path = self.preprocessed_root / f"{cell_id}_profiles_{self.mode}128.npz"
        if not path.is_file():
            raise FileNotFoundError(path)
        return path
